def acquire_pair_input(path: Path):
    """Acquire the bounded observed PRISM pair cube through the public loader."""

    if path.exists():
        print(f"using existing observed pair input: {path}")
        return
    import cubedynamics as cd

    path.parent.mkdir(parents=True, exist_ok=True)
    source = cd.load_prism_cube(
        variables=["tmin", "tmax"],
        start="2023-11-01",
        end="2024-01-30",
        bbox=[-105.75, 39.50, -104.75, 40.50],
        freq="D",
        chunks={"time": 31, "y": 64, "x": 64},
        prefer_streaming=True,
        show_progress=False,
        allow_synthetic=False,
    )
    if bool(source.attrs.get("is_synthetic", True)):
        raise RuntimeError("Refusing synthetic PRISM input")
    observed = source.compute()
    observed.attrs.update(dict(source.attrs))
    observed.to_netcdf(path, engine="scipy")
    print(f"acquired observed pair input: {path}")


def _nearest_index(values, target, np) -> int:
    target64 = np.datetime64(target)
    return int(np.argmin(np.abs(values.astype("datetime64[ns]") - target64)))


def _coord_index(values, target, np) -> int:
    return int(np.argmin(np.abs(np.asarray(values, dtype=float) - float(target))))


def _manual_spearman(left, right, mask, np, rankdata) -> float:
    left_rank = rankdata(np.asarray(left)[mask], method="average")
    right_rank = rankdata(np.asarray(right)[mask], method="average")
    return float(np.corrcoef(left_rank, right_rank)[0, 1])


