def _binned_median(frame, x_name, y_name, pd, np, bins=9):
    clean = frame[[x_name, y_name]].dropna().copy()
    clean["bin"] = pd.cut(clean[x_name], bins=np.linspace(clean[x_name].min(), clean[x_name].max(), bins + 1), include_lowest=True)
    grouped = clean.groupby("bin", observed=True).agg({x_name: "median", y_name: "median"}).dropna()
    return grouped[x_name].to_numpy(), grouped[y_name].to_numpy()


