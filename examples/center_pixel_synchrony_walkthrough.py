def compose_pdf(page_paths: list[Path], pdf_path: Path):
    try:
        from reportlab.lib.utils import ImageReader
        from reportlab.pdfgen import canvas
    except ImportError as exc:
        raise RuntimeError(
            "PDF composition requires reportlab. Install it or run --compose-only "
            "with the bundled Codex PDF runtime."
        ) from exc

    width = PAGE_WIDTH * 72
    height = PAGE_HEIGHT * 72
    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    document = canvas.Canvas(str(pdf_path), pagesize=(width, height), pageCompression=1)
    document.setTitle("Center-pixel climate synchrony: a visual walkthrough")
    document.setAuthor("CubeDynamics")
    document.setSubject("Observed PRISM center-reference rolling climate-tail synchrony")
    for path in page_paths:
        document.drawImage(ImageReader(str(path)), 0, 0, width=width, height=height, preserveAspectRatio=False, mask="auto")
        document.showPage()
    document.save()


