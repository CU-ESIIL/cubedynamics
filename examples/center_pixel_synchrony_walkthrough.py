    center_col = "center_tmax_degC" if warm else "center_tmin_degC"
    focal_col = "focal_tmax_degC" if warm else "focal_tmin_degC"
    mask_col = "jointly_warm" if warm else "jointly_cold"
    mask = frame[mask_col].to_numpy()
    center = frame[center_col].to_numpy(); focal = frame[focal_col].to_numpy()
    center_median = pair["warm_center_median"] if warm else pair["cold_center_median"]
    focal_median = pair["warm_focal_median"] if warm else pair["cold_focal_median"]
