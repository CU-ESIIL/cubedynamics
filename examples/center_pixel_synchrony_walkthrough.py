def _map_extent(da):
    x = da["x"].values
    y = da["y"].values
    dx = abs(float(x[1] - x[0])) if len(x) > 1 else 1.0
    dy = abs(float(y[1] - y[0])) if len(y) > 1 else 1.0
    return [float(x.min() - dx / 2), float(x.max() + dx / 2), float(y.min() - dy / 2), float(y.max() + dy / 2)]


def _plot_center_focal(ax, center_coord, focal_coord, *, center_label=True, focal_label=True):
    cy, cx = center_coord
    fy, fx = focal_coord
    ax.scatter(cx, cy, marker="*", s=230, color=CENTER, edgecolor=INK, linewidth=1.3, zorder=8)
    ax.scatter(fx, fy, marker="D", s=85, color=FOCAL, edgecolor=WHITE, linewidth=1.2, zorder=8)
    if center_label:
        ax.annotate("CENTER", (cx, cy), xytext=(8, 8), textcoords="offset points", fontsize=9, weight="bold", color=INK)
    if focal_label:
        ax.annotate("FOCAL", (fx, fy), xytext=(8, -14), textcoords="offset points", fontsize=9, weight="bold", color=FOCAL)


def _clean_axis(ax):
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(color=GRID, linewidth=0.7, alpha=0.65)


