def _load_and_verify(pair_input: Path, full_sync: Path, full_manifest: Path, modules):
    np = modules["np"]
    pd = modules["pd"]
    rankdata = modules["rankdata"]
    xr = modules["xr"]

    from cubedynamics import pipe, verbs as v
    from cubedynamics.synchrony.spatial import build_spatial_pairs
    from cubedynamics.utils.reference import center_pixel_indices

    if not pair_input.exists():
        raise FileNotFoundError(
            f"Missing observed 90-day PRISM input: {pair_input}. "
            "See the walkthrough README for the bounded acquisition command."
        )
    if not full_sync.exists() or not full_manifest.exists():
        raise FileNotFoundError(
            "Missing full-record PRISM synchrony artifact. Run "
            "examples/real_prism_median_split_synchrony.py first."
        )

    with xr.open_dataset(pair_input, engine="scipy") as source:
        pair_cube = source[["tmin", "tmax"]].load()
    if bool(pair_cube.attrs.get("is_synthetic", True)):
        raise RuntimeError("Pair-level input must be observed PRISM data")
    if pair_cube.sizes["time"] != 91:
        raise RuntimeError("Expected 91 inclusive daily labels in the 90-day span")

    center_y, center_x = center_pixel_indices(pair_cube["tmin"])
    focal_y = _coord_index(pair_cube["y"].values, FOCAL_COORD[0], np)
    focal_x = _coord_index(pair_cube["x"].values, FOCAL_COORD[1], np)
    end_time = pair_cube["time"].values[-1]

    synchrony = (
        pipe(pair_cube)
        | v.rolling_median_split_synchrony(
            lower_var="tmin",
            upper_var="tmax",
            window_days=WINDOW_DAYS,
            min_t=MIN_T,
            split_quantile=SPLIT_QUANTILE,
            output_stride=OUTPUT_STRIDE,
            output_times=[end_time],
        )
    ).unwrap().compute()

    cold_center = pair_cube["tmin"].isel(y=center_y, x=center_x).values
    cold_focal = pair_cube["tmin"].isel(y=focal_y, x=focal_x).values
    warm_center = pair_cube["tmax"].isel(y=center_y, x=center_x).values
    warm_focal = pair_cube["tmax"].isel(y=focal_y, x=focal_x).values

    cold_valid = np.isfinite(cold_center) & np.isfinite(cold_focal)
    warm_valid = np.isfinite(warm_center) & np.isfinite(warm_focal)
    cold_center_median = float(np.quantile(cold_center[cold_valid], SPLIT_QUANTILE))
    cold_focal_median = float(np.quantile(cold_focal[cold_valid], SPLIT_QUANTILE))
    warm_center_median = float(np.quantile(warm_center[warm_valid], 1 - SPLIT_QUANTILE))
    warm_focal_median = float(np.quantile(warm_focal[warm_valid], 1 - SPLIT_QUANTILE))
    cold_mask = (
        cold_valid
        & (cold_center <= cold_center_median)
        & (cold_focal <= cold_focal_median)
    )
    warm_mask = (
        warm_valid
        & (warm_center > warm_center_median)
        & (warm_focal > warm_focal_median)
    )
    manual_cold = _manual_spearman(cold_center, cold_focal, cold_mask, np, rankdata)
    manual_warm = _manual_spearman(warm_center, warm_focal, warm_mask, np, rankdata)
    package_cold = float(synchrony["bottom_synchrony"].isel(time_window_end=0, y=focal_y, x=focal_x))
    package_warm = float(synchrony["top_synchrony"].isel(time_window_end=0, y=focal_y, x=focal_x))
    package_difference = float(synchrony["bottom_minus_top"].isel(time_window_end=0, y=focal_y, x=focal_x))
    np.testing.assert_allclose(manual_cold, package_cold, rtol=0, atol=1e-7)
    np.testing.assert_allclose(manual_warm, package_warm, rtol=0, atol=1e-7)
    np.testing.assert_allclose(package_difference, package_cold - package_warm, rtol=0, atol=1e-7)

    pair_set = build_spatial_pairs(pair_cube["tmin"], mode="reference", reference="center")
    focal_flat = focal_y * pair_cube.sizes["x"] + focal_x
    focal_distance = float(pair_set.distances[focal_flat])
    frame = pd.DataFrame(
        {
            "time": pd.DatetimeIndex(pair_cube["time"].values),
            "center_tmin_degC": cold_center,
            "focal_tmin_degC": cold_focal,
            "center_tmax_degC": warm_center,
            "focal_tmax_degC": warm_focal,
            "jointly_cold": cold_mask,
            "jointly_warm": warm_mask,
        }
    )
    pair = {
        "cube": pair_cube,
        "synchrony": synchrony,
        "frame": frame,
        "center_index": (center_y, center_x),
        "focal_index": (focal_y, focal_x),
        "center_coord": (float(pair_cube["y"][center_y]), float(pair_cube["x"][center_x])),
        "focal_coord": (float(pair_cube["y"][focal_y]), float(pair_cube["x"][focal_x])),
        "distance_km": focal_distance,
        "cold_center_median": cold_center_median,
        "cold_focal_median": cold_focal_median,
        "warm_center_median": warm_center_median,
        "warm_focal_median": warm_focal_median,
        "cold_count": int(cold_mask.sum()),
        "warm_count": int(warm_mask.sum()),
        "cold_rho": package_cold,
        "warm_rho": package_warm,
        "difference": package_difference,
    }

    with xr.open_dataset(full_sync, engine="scipy") as source:
        full = source.load()
    manifest = json.loads(full_manifest.read_text(encoding="utf-8"))
    if bool(manifest.get("is_synthetic", True)):
        raise RuntimeError("Full-record synchrony input must be observed PRISM data")
    snapshot_index = _nearest_index(full["time_window_end"].values, SNAPSHOT_TARGET, np)
    snapshot = full.isel(time_window_end=snapshot_index).copy()
    snapshot_time = pd.Timestamp(full["time_window_end"].values[snapshot_index])

    full_center_y, full_center_x = center_pixel_indices(full["bottom_synchrony"])
    snapshot_pairs = build_spatial_pairs(
        full["bottom_synchrony"], mode="reference", reference="center"
    )
    flat_y, flat_x = np.meshgrid(
        np.arange(full.sizes["y"]), np.arange(full.sizes["x"]), indexing="ij"
    )
    distance_frame = pd.DataFrame(
        {
            "y_index": flat_y.ravel(),
            "x_index": flat_x.ravel(),
            "latitude": np.repeat(full["y"].values, full.sizes["x"]),
            "longitude": np.tile(full["x"].values, full.sizes["y"]),
            "distance_km": np.asarray(snapshot_pairs.distances),
            "cold_synchrony": snapshot["bottom_synchrony"].values.ravel(),
            "warm_synchrony": snapshot["top_synchrony"].values.ravel(),
            "cold_minus_warm": snapshot["bottom_minus_top"].values.ravel(),
        }
    )
    regional = full.median(dim=("y", "x"), skipna=True)
    regional_frame = regional.to_dataframe().reset_index()
    full_context = {
        "full": full,
        "snapshot": snapshot,
        "snapshot_time": snapshot_time,
        "manifest": manifest,
        "center_index": (full_center_y, full_center_x),
        "center_coord": (float(full["y"][full_center_y]), float(full["x"][full_center_x])),
        "distance_frame": distance_frame,
        "regional_frame": regional_frame,
    }
    return pair, full_context


